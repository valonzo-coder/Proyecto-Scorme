          if (rt.interactedIds.length > 0) entry.i = rt.interactedIds;
          if (rt.openedResourceIds.length > 0) entry.o = rt.openedResourceIds;
          if (rt.confirmedResourceIds.length > 0) entry.f = rt.confirmedResourceIds;
